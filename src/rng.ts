/**
 * Small seeded generator (mulberry32): themes use it to pick stable art per card, tests and bots
 * to replay a run. The engine has the same generator in Rust (crates/engine/src/deck.rs).
 */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
